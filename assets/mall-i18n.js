export const MALL_COPY = Object.freeze(
  Object.fromEntries(
    Object.entries(copy).map(([locale, values]) => [locale, Object.freeze(values)]),
  ),
);

export function getMallLocale(pathname = window.location.pathname) {
  const path = pathname.toLowerCase();
  if (path === "/zh" || path.startsWith("/zh/")) return MALL_COPY.zh;
  if (path === "/fa" || path.startsWith("/fa/")) return MALL_COPY.fa;
  return MALL_COPY.en;
}
